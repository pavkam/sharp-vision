namespace SharpVision.Showcase.Panes;

/// <summary>Selects where a showcase panel draws its caption relative to body content.</summary>
public enum LabelPlacement
{
    /// <summary>Draws the caption to the left of the body text.</summary>
    Left,

    /// <summary>Draws the caption to the right of the body text.</summary>
    Right,

    /// <summary>Draws the caption above the body text.</summary>
    Above,

    /// <summary>Draws the caption below the body text.</summary>
    Below,
}
