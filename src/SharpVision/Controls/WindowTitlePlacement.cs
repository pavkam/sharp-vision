namespace SharpVision.Controls;

/// <summary>Selects where a Window title is placed along its top frame edge.</summary>
public enum WindowTitlePlacement
{
    /// <summary>Places the title immediately after the top-left corner.</summary>
    Left,

    /// <summary>Centers the title between the top frame corners.</summary>
    Center,

    /// <summary>Places the title immediately before the top-right corner.</summary>
    Right,
}
