namespace SharpVision.Controls;

/// <summary>Identifies one built-in ChaseIndicator active and inactive glyph pair.</summary>
public enum ChasePattern
{
    /// <summary>Uses a filled and hollow circle.</summary>
    Circle,

    /// <summary>Uses a filled and hollow diamond.</summary>
    Diamond,

    /// <summary>Uses a filled and hollow square.</summary>
    Square,

    /// <summary>Uses filled and hollow upward triangles.</summary>
    Up,

    /// <summary>Uses filled and hollow downward triangles.</summary>
    Down,

    /// <summary>Uses filled and hollow left-pointing triangles.</summary>
    Left,

    /// <summary>Uses filled and hollow right-pointing triangles.</summary>
    Right,
}
