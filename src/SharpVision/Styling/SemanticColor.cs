namespace SharpVision.Styling;

/// <summary>Identifies one library-defined global theme color.</summary>
public enum SemanticColor
{
    /// <summary>The application window background.</summary>
    Window,
    /// <summary>Text drawn on the application window.</summary>
    WindowText,
    /// <summary>A raised or contained surface background.</summary>
    Surface,
    /// <summary>Text drawn on a raised or contained surface.</summary>
    SurfaceText,
    /// <summary>The ordinary control background.</summary>
    Control,
    /// <summary>The ordinary control text.</summary>
    ControlText,
    /// <summary>The ordinary control border.</summary>
    ControlBorder,
    /// <summary>The ordinary control shadow.</summary>
    ControlShadow,
    /// <summary>The illuminated edge of raised or sunken relief.</summary>
    ReliefHighlight,
    /// <summary>The shaded edge of raised or sunken relief.</summary>
    ReliefShade,
    /// <summary>The active control background.</summary>
    ActiveControl,
    /// <summary>The active control text.</summary>
    ActiveText,
    /// <summary>The active control border.</summary>
    ActiveBorder,
    /// <summary>The focused control background.</summary>
    FocusedControl,
    /// <summary>The focused control text.</summary>
    FocusedText,
    /// <summary>The focused control border.</summary>
    FocusedBorder,
    /// <summary>The pressed control background.</summary>
    PressedControl,
    /// <summary>The pressed control text.</summary>
    PressedText,
    /// <summary>The pressed control border.</summary>
    PressedBorder,
    /// <summary>The selected-item background.</summary>
    SelectedControl,
    /// <summary>The selected-item text.</summary>
    SelectedText,
    /// <summary>The disabled control background.</summary>
    DisabledControl,
    /// <summary>The disabled control text.</summary>
    DisabledText,
    /// <summary>The disabled control border.</summary>
    DisabledBorder,
    /// <summary>The general accent color.</summary>
    Accent,
    /// <summary>The muted secondary color.</summary>
    Muted,
    /// <summary>The access-key highlight color.</summary>
    Hotkey,
    /// <summary>The error status color.</summary>
    Error,
    /// <summary>The warning status color.</summary>
    Warning,
    /// <summary>The success status color.</summary>
    Success,
    /// <summary>The informational status color.</summary>
    Info,
    /// <summary>The raised background of a floating Window or dialog.</summary>
    WindowSurface,
    /// <summary>The theme's canonical red accent, for differentiating chart series, syntax tokens, and similar content.</summary>
    Red,
    /// <summary>The theme's canonical green accent, for differentiating chart series, syntax tokens, and similar content.</summary>
    Green,
    /// <summary>The theme's canonical yellow accent, for differentiating chart series, syntax tokens, and similar content.</summary>
    Yellow,
    /// <summary>The theme's canonical blue accent, for differentiating chart series, syntax tokens, and similar content.</summary>
    Blue,
    /// <summary>The theme's canonical magenta accent, for differentiating chart series, syntax tokens, and similar content.</summary>
    Magenta,
    /// <summary>The theme's canonical cyan accent, for differentiating chart series, syntax tokens, and similar content.</summary>
    Cyan,
    /// <summary>The raised navigation background shared by menu, command, and status bars.</summary>
    Bar
}
