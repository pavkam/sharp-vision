namespace SharpVision.Terminal.Rendering;

/// <summary>Defines standard Unicode shade and solid block fills.</summary>
public enum Shade
{
    /// <summary>Uses U+2591 LIGHT SHADE.</summary>
    Light,

    /// <summary>Uses U+2592 MEDIUM SHADE.</summary>
    Medium,

    /// <summary>Uses U+2593 DARK SHADE.</summary>
    Dark,

    /// <summary>Uses U+2588 FULL BLOCK.</summary>
    Solid,
}
